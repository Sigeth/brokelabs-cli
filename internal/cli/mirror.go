// mirrorService is the Service of the registry mirror in the platform namespace.
const mirrorService = project.Name + "-mirror"

// mirrorPort is the port of the registry mirror.
const mirrorPort = "5000"

// defaultMirroredRegistries are the upstream registries nodes pull through
// the mirror by default.
var defaultMirroredRegistries = []string{"ghcr.io", "docker.io", "quay.io", "registry.k8s.io"}

func newMirrorCommand() *cobra.Command {
	var kubeconfig, kubeContext string
	cmd := &cobra.Command{
		Use:   "mirror",
		Short: "Configure nodes to pull through the in-cluster registry mirror",
	}
	cmd.PersistentFlags().StringVar(&kubeconfig, "kubeconfig", "", "kubeconfig file (default: $KUBECONFIG or ~/.kube/config)")
	cmd.PersistentFlags().StringVar(&kubeContext, "context", "", "kubeconfig context (default: the current one)")

	var (
		endpoint   string
		namespace  = defaultSystemNamespace
		registries = defaultMirroredRegistries
	)
	nodeConfig := &cobra.Command{
		Use:   "node-config",
		Short: "Print the k3s registries.yaml sending pulls to the mirror",
		Long: "Prints a k3s registries.yaml in which every listed registry is mirrored by the in-cluster\n" +
			"registry (D39): containerd asks the mirror first, under <registry>/<repository>, and falls back\n" +
			"to the registry itself. Install it on every node, then restart k3s:\n\n" +
			"  " + project.Name + " mirror node-config | sudo tee /etc/rancher/k3s/registries.yaml\n" +
			"  sudo systemctl restart k3s   # k3s-agent on agent nodes\n\n" +
			"The endpoint is the ClusterIP of the mirror Service (nodes cannot resolve cluster DNS):\n" +
			"pin it with the chart value mirror.service.clusterIP so it never changes.\n" +
			"Images of registries that are not listed are pulled from those registries.",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if endpoint == "" {
				c, err := kube.Connect(kubeconfig, kubeContext)
				if err != nil {
					return err
				}
				if endpoint, err = mirrorEndpoint(cmd.Context(), c, namespace); err != nil {
					return err
				}
			}
			return writeRegistriesConfig(cmd.OutOrStdout(), endpoint, registries)
		},
	}
	nodeConfig.Flags().StringVar(&endpoint, "endpoint", "", "address of the mirror as nodes reach it (host:port; default: the ClusterIP of its Service)")
	nodeConfig.Flags().StringVarP(&namespace, "namespace", "n", namespace, "namespace of the platform")
	nodeConfig.Flags().StringSliceVar(&registries, "registries", registries, "registries pulled through the mirror")
	cmd.AddCommand(nodeConfig)
	return cmd
}

// mirrorEndpoint returns the ClusterIP and port of the mirror Service.
func mirrorEndpoint(ctx context.Context, c *kube.Cluster, namespace string) (string, error) {
	svc, err := c.Client.CoreV1().Services(namespace).Get(ctx, mirrorService, metav1.GetOptions{})
	if err != nil {
		return "", fmt.Errorf("finding the registry mirror (is the platform installed with mirror.enabled?): %w", err)
	}
	if ip := svc.Spec.ClusterIP; ip == "" || ip == "None" {
		return "", fmt.Errorf("service %s/%s has no ClusterIP", namespace, mirrorService)
	}
	return net.JoinHostPort(svc.Spec.ClusterIP, mirrorPort), nil
}

// registriesConfig is the part of k3s' registries.yaml written here.
type registriesConfig struct {
	Mirrors map[string]registryMirror `json:"mirrors"`
}

type registryMirror struct {
	Endpoint []string          `json:"endpoint"`
	Rewrite  map[string]string `json:"rewrite"`
}

// writeRegistriesConfig writes a registries.yaml mirroring registries
// through endpoint, rewriting repository paths the way the operator stores
// them (mirror/<registry>/<repository>, a port written "_<port>").
func writeRegistriesConfig(out io.Writer, endpoint string, registries []string) error {
	if _, _, err := net.SplitHostPort(endpoint); err != nil {
		return fmt.Errorf("--endpoint %q: want host:port", endpoint)
	}
	cfg := registriesConfig{Mirrors: map[string]registryMirror{}}
	for _, r := range registries {
		r = strings.TrimSpace(r)
		if r == "" || strings.ContainsAny(r, "/ ") {
			return fmt.Errorf("%q: not a registry host", r)
		}
		cfg.Mirrors[r] = registryMirror{
			Endpoint: []string{"http://" + endpoint},
			Rewrite:  map[string]string{"^(.*)$": strings.ReplaceAll(r, ":", "_") + "/$1"},
		}
	}
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return err
	}
	names := slices.Sorted(maps.Keys(cfg.Mirrors))
	fmt.Fprintf(out, "# Generated by %s mirror node-config: %s pulled through %s.\n", project.Name, strings.Join(names, ", "), endpoint)
	_, err = out.Write(data)
	return err
}
